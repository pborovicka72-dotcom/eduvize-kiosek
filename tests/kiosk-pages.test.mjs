import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const scope={window:{}};
vm.runInNewContext(fs.readFileSync(new URL('../kiosk-pages.js',import.meta.url),'utf8'),scope);
const pages=scope.window.EduvizeKioskPages;
const config={pages:[{id:'home',title:'Hlavní nabídka',buttons:[]}]};
const parent=pages.create(config,'home','parents');
pages.rename(config,parent.id,'Pro rodiče');
assert.equal(config.pages[0].buttons[0].target,parent.id);
assert.equal(config.pages[0].buttons[0].label,'Pro rodiče');
config.pages[0].buttons.push({type:'page',target:parent.id,label:'Vlastní popisek'});
pages.rename(config,parent.id,'Rodiče');
assert.equal(config.pages[0].buttons[1].label,'Vlastní popisek');
const child=pages.create(config,parent.id,'documents');
assert.equal(parent.buttons[0].target,child.id);
const duplicate=pages.create(config,'home','documents');
assert.notEqual(child.id,duplicate.id);
assert.equal(pages.remove(config,child.id),true);
assert.equal(parent.buttons.length,0);
assert.equal(pages.remove(config,'home'),false);
assert.ok(config.pages.some(page=>page.id==='home'));
console.log('Page hierarchy passed.');
